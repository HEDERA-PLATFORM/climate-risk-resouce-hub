#!/usr/bin/env python3
"""
convert.py — Excel → JS data file converter
============================================
Usage:
    python tools/convert.py resources          # converts resources.xlsx → data/resources.js
    python tools/convert.py datasets           # converts datasets.xlsx  → data/datasets.js
    python tools/convert.py all                # converts all configured sheets

Spreadsheet rules:
    - First row = column headers (exact names defined in SCHEMAS below)
    - One row per record
    - Tags/topics: comma-separated values in a single cell, e.g.  "climate risk, finance, TCFD"
    - Lists (variables, formats, links): see schema comments below
    - Empty cells are allowed; mandatory fields are flagged as warnings
    - Extra columns are silently ignored
"""

import sys
import json
import re
import textwrap
from pathlib import Path
from datetime import datetime

try:
    import pandas as pd
except ImportError:
    sys.exit("pandas is required: pip install pandas openpyxl")

# ── Paths ─────────────────────────────────────────────────────────────────────
ROOT        = Path(__file__).parent.parent          # project root
EXCEL_DIR   = Path(__file__).parent / "source-excel"
DATA_DIR    = ROOT / "site" / "data"
DATA_DIR.mkdir(parents=True, exist_ok=True)

# ── Helpers ───────────────────────────────────────────────────────────────────
def split_list(value, sep=","):
    """Turn a comma-separated string into a cleaned list; empty → []."""
    if pd.isna(value) or str(value).strip() == "":
        return []
    return [s.strip() for s in str(value).split(sep) if s.strip()]

def clean_str(value, default=""):
    """Return a stripped string or default if NaN/empty."""
    if pd.isna(value):
        return default
    s = str(value).strip()
    return s if s else default

def parse_links(value):
    """
    Parse one or more links from a cell.
    Accepted formats (pick ONE per spreadsheet, be consistent):
        1. Single URL:         https://example.com
        2. Label|URL pairs, one per line:
               Dataset portal|https://example.com
               API docs|https://api.example.com
    Returns: [{"label": "...", "url": "..."}, ...]
    """
    raw = clean_str(value)
    if not raw:
        return []
    links = []
    for line in raw.splitlines():
        line = line.strip()
        if not line:
            continue
        if "|" in line:
            parts = line.split("|", 1)
            links.append({"label": parts[0].strip(), "url": parts[1].strip()})
        else:
            # bare URL — use a default label
            links.append({"label": "Open", "url": line})
    return links

def to_js(const_name, records, source_file):
    """Wrap a list of dicts as a JS const declaration."""
    source  = source_file.name if source_file else "unknown"
    ts      = datetime.now().strftime("%Y-%m-%d %H:%M")
    payload = json.dumps(records, ensure_ascii=False, indent=2)
    return textwrap.dedent(f"""\
        /* AUTO-GENERATED by tools/convert.py — do not edit by hand.
           Source: tools/source-excel/{source}
           Generated: {ts}
           Re-generate: python tools/convert.py {const_name.lower()} */

        const {const_name} = {payload};
    """)

def warn(row_num, field, msg):
    print(f"  ⚠  row {row_num+2}: {field} — {msg}")

